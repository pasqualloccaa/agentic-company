"""What each agent remembers: the Italian briefing it receives at every turn.

Memory = the last complete turns in detail + a summary of the older weeks
(generated by code, so it is free and reproducible) + the agent's own diary.
The board only sees the reports it received and the minutes, never the ledger.
System prompt and briefing together stay under TOKEN_BUDGET; the oldest diary
entries and summary lines are dropped first.
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from typing import Any

from .. import kpis
from ..engine import Action
from ..governance import Governance
from .personas import num_it

TOKEN_BUDGET = 15_000
CHARS_PER_TOKEN = 3.0      # conservative for Italian text without a tokenizer
DETAILED_TURNS = 2
HEADLINE = ("revenue", "ebitda", "cash", "nfp", "nfp_ebitda", "revolver_available")


def estimate_tokens(text: str) -> int:
    return math.ceil(len(text) / CHARS_PER_TOKEN)


@dataclass
class TurnRecord:
    week: int
    actor: str
    text: str                      # the agent's closing summary
    first_seq: int                 # attempts made during the turn: first_seq..last_seq
    last_seq: int
    usage: dict[str, Any] = field(default_factory=dict)


# ------------------------------------------------------------------ formatting

def fmt_value(key: str, value: float) -> str:
    unit = kpis.KPI_DEFS[key].unit
    if not math.isfinite(value):
        return "n.d."
    if unit == "EUR":
        return f"{num_it(value)} euro"
    if unit == "%":
        return f"{num_it(value, 1)}%"
    if unit == "x":
        return num_it(value, 2)
    return num_it(value)


def describe(action: Action, sim) -> str:
    p = action.params
    if action.kind == "set_price":
        name = sim.customers[p["customer"]]["name"]
        return f"variazione del prezzo al cliente {p['customer']} ({name}) del {num_it(100 * p['pct'], 1)}%"
    if action.kind == "approve_spend":
        return (f"spesa {p['category']} di {num_it(p['amount'])} euro verso {p['counterparty']}: "
                f"{p['description']}")
    return f"{action.kind} {json.dumps(p, ensure_ascii=False)}"


def _compact(params: dict[str, Any], limit: int = 160) -> str:
    text = json.dumps(params, ensure_ascii=False)
    return text if len(text) <= limit else text[:limit] + "…"


def _week_events(sim, week: int) -> list[str]:
    return [e.note for e in sim.events if e.week == week and e.type in ("shock", "event", "bank_review")]


def _turn_lines(gov: Governance, turn: TurnRecord, events: list[str] | None = None) -> list[str]:
    lines = [f"### Settimana {turn.week}"]
    lines += [f"Evento: {e}" for e in events or []]
    for a in gov.attempts[turn.first_seq - 1:turn.last_seq]:
        why = f" ({'; '.join(a.reasons)})" if a.reasons else ""
        lines.append(f"- {a.tool} {_compact(a.params)} → {a.outcome}{why}")
    lines.append(f"Tuo riepilogo: {turn.text.strip() or '(nessuno)'}")
    return lines


def _diary(gov: Governance, actor: str) -> list[str]:
    return [f"- Settimana {d.week}: {d.text}" for d in gov.diaries if d.actor == actor]


def _agenda(gov: Governance, sim) -> list[str]:
    items = [i for i in gov.agenda if i.status == "open"]
    if not items:
        return ["Nessun punto aperto."]
    return [f"- Punto {i.item_id} (proposto in settimana {i.week}): {describe(i.action, sim)}. "
            f"Motivo: {'; '.join(i.reasons)}" for i in items]


def _minutes(gov: Governance, weeks: range) -> list[str]:
    out = []
    for m in gov.minutes:
        if m.week in weeks:
            verb = "approvato" if m.decision == "approve" else "respinto"
            out.append(f"- Settimana {m.week}, punto {m.item_id} {verb}: {m.motivation}")
    return out


# ------------------------------------------------------------------ fitting

@dataclass
class Section:
    title: str
    lines: list[str]
    trim_priority: int | None = None   # lower is trimmed first; None = never trimmed

    def render(self) -> str:
        return f"## {self.title}\n" + "\n".join(self.lines) if self.title else "\n".join(self.lines)


def fit(sections: list[Section], budget_tokens: int) -> str:
    """Join sections, dropping the oldest lines of trimmable sections until within budget."""
    def text() -> str:
        return "\n\n".join(s.render() for s in sections if s.lines)

    trimmable = [s for s in sections if s.trim_priority is not None]
    for section in sorted(trimmable, key=lambda s: s.trim_priority or 0):
        while estimate_tokens(text()) > budget_tokens and section.lines:
            section.lines.pop(0)
    out = text()
    if estimate_tokens(out) > budget_tokens:
        raise ValueError("Briefing does not fit in the token budget even after trimming")
    return out


def _last_turns(turns: list[TurnRecord], actor: str, week: int) -> list[TurnRecord]:
    return [t for t in turns if t.actor == actor and t.week < week][-DETAILED_TURNS:]


# ------------------------------------------------------------------ briefings

def uffici_briefing(sim, gov: Governance, turns: list[TurnRecord], budget_tokens: int,
                    next_meeting: int) -> str:
    w = gov.week
    news = [f"- {note}" for note in _week_events(sim, w)]
    news += _minutes(gov, range(w - 1, w))
    week_kpis = kpis.compute_all(sim, w, w)
    detailed = _last_turns(turns, "uffici", w)
    first_detailed = detailed[0].week if detailed else w
    summary = []
    for k in range(1, first_detailed):
        values = kpis.compute_all(sim, k, k)
        events = "; ".join(_week_events(sim, k))
        own = [a for a in gov.attempts if a.week == k and a.actor == "uffici"
               and a.tool not in ("get_kpis", "read_ledger", "write_diary")]
        summary.append(f"- Sett. {k}: ricavi {fmt_value('revenue', values['revenue'])}, EBITDA "
                       f"{fmt_value('ebitda', values['ebitda'])}, cassa {fmt_value('cash', values['cash'])}, "
                       f"PFN/EBITDA {fmt_value('nfp_ebitda', values['nfp_ebitda'])}"
                       + (f"; eventi: {events}" if events else "")
                       + (f"; tue azioni: {', '.join(f'{a.tool} → {a.outcome}' for a in own)}" if own else ""))
    meeting = ("stasera, dopo il tuo turno" if next_meeting == w else f"in settimana {next_meeting}")
    now = [f"È la chiusura della settimana {w}. Il prossimo CdA si riunisce {meeting}.",
           "Usa gli strumenti per decidere e comunicare, poi annota nel diario ciò che vuoi ricordare "
           "e chiudi con un breve riepilogo."]
    sections = [
        Section("", [f"# Briefing di fine settimana {w}"]),
        Section("Novità della settimana", news or ["Nessuna novità particolare."]),
        Section(f"Conti della settimana {w} (dalla contabilità)",
                [f"- {kpis.KPI_DEFS[k].label}: {fmt_value(k, week_kpis[k])}" for k in HEADLINE]),
        Section("Ordine del giorno del CdA, punti aperti", _agenda(gov, sim)),
        Section("Decisioni del CdA finora", _minutes(gov, range(0, w)), trim_priority=3),
        Section("Le tue ultime settimane",
                [l for t in detailed for l in _turn_lines(gov, t, _week_events(sim, t.week))]),
        Section("Riepilogo delle settimane precedenti", summary, trim_priority=2),
        Section("Dal tuo diario", _diary(gov, "uffici"), trim_priority=1),
        Section("Ora", now),
    ]
    return fit(sections, budget_tokens)


def _report_lines(report, full: bool) -> list[str]:
    lines = [f"### Report n. {report.report_id}, ricevuto in settimana {report.week} "
             f"(periodo: settimane {report.week_from}-{report.week_to})"]
    lines += [f"- {kpis.KPI_DEFS[k].label}: {fmt_value(k, v)}" for k, v in report.kpis.items()]
    if full:
        lines.append(f"Commento degli Uffici: {report.narrative}")
    return lines


def cda_briefing(sim, gov: Governance, turns: list[TurnRecord], budget_tokens: int) -> str:
    w, since = gov.week, gov.last_meeting_week
    new = [r for r in gov.reports if r.week > since]
    old = [r for r in gov.reports if r.week <= since]
    detailed = _last_turns(turns, "cda", w)
    items = [i for i in gov.agenda if i.status == "open"]
    now = [f"La riunione della settimana {w} è aperta."]
    if items:
        now.append("Delibera su ciascun punto all'ordine del giorno con deliberate, poi annota nel diario "
                   "ciò che vuoi ricordare e chiudi con un breve riepilogo.")
    else:
        now.append("Non ci sono punti da deliberare. Annota nel diario ciò che vuoi ricordare e chiudi "
                   "con un breve riepilogo.")
    sections = [
        Section("", [f"# Riunione del Consiglio di amministrazione, settimana {w}"]),
        Section("Report ricevuti dagli Uffici dall'ultima riunione",
                [l for r in new for l in _report_lines(r, full=True)] or
                ["Nessun report ricevuto dall'ultima riunione."]),
        Section("Ordine del giorno", _agenda(gov, sim)),
        Section("Report precedenti", [l for r in old for l in _report_lines(r, full=False)], trim_priority=3),
        Section("Verbali delle riunioni precedenti", _minutes(gov, range(0, w)), trim_priority=2),
        Section("Le tue ultime riunioni", [l for t in detailed for l in _turn_lines(gov, t)]),
        Section("Dal tuo diario", _diary(gov, "cda"), trim_priority=1),
        Section("Ora", now),
    ]
    return fit(sections, budget_tokens)
